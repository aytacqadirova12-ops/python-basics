# 10 -> Təxminim: int
print(type(10))

# 10.0 -> Təxminim: float
print(type(10.0))

# "10" -> Təxminim: str
print(type("10"))

# True -> Təxminim: bool
print(type(True))

# "True" -> Təxminim: str
print(type("True"))

# 3 + 2.0 -> Təxminim: float
print(type(3 + 2.0))

# "3" + "2" -> Təxminim: str
print(type("3" + "2"))

# 10 / 2 -> Təxminim: float 
print(type(10 / 2))

